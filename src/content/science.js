export function scienceQuestions(subject, day, stage, date, seen = {}) {
  const pack = packs[subject]?.[day];
  if (!pack || ![0, 1].includes(stage)) throw Error("内容包不存在");
  const rows = pack[3].slice(stage ? 4 : 0, stage ? 6 : 4);
  return rows.map((r, i) => {
    const contentId = `${subject}-w1-d${day + 1}-q${stage ? i + 5 : i + 1}`;
    if (seen[contentId]) throw Error("这组内容已经学过，不重复发同一题");
    seen[contentId] = true;
    const choices = hash(contentId) % 2 ? [r[1], r[2]] : [r[2], r[1]];
    return {
      id: contentId,
      subject,
      day,
      stage,
      chapter: pack[1],
      topic: pack[0],
      template: `${subject}-day${day + 1}`,
      visual: pack[2],
      prompt: r[0],
      choices,
      answer: r[1],
      hint: r[3],
      solution: r[4],
    };
  });
}
export function validateScienceSession(s) {
  if (
    !["biology", "geography"].includes(s.subject) ||
    ![0, 1].includes(s.stage) ||
    !Number.isInteger(s.day) ||
    s.day < 0 ||
    s.day > 6 ||
    !/^\d{4}-\d{2}-\d{2}$/.test(s.date) ||
    s.id !== `${s.subject}:${s.date}:${s.stage}` ||
    !Array.isArray(s.questions) ||
    s.questions.length !== (s.stage ? 2 : 4) ||
    !Array.isArray(s.records) ||
    s.records.length !== s.questions.length ||
    !Number.isInteger(s.index) ||
    s.index < 0 ||
    s.index > s.questions.length ||
    s.completed !== (s.index === s.questions.length)
  )
    throw Error("科学探索存档无效");
  const expected = scienceQuestions(s.subject, s.day, s.stage, s.date);
  s.questions.forEach((q, i) => {
    if (JSON.stringify(q) !== JSON.stringify(expected[i]))
      throw Error("科学题目内容不一致");
    const r = s.records[i];
    if (
      !r ||
      !Array.isArray(r.input) ||
      r.input.length > 1 ||
      !r.input.every((v) => q.choices.includes(v)) ||
      !Number.isSafeInteger(r.errors) ||
      r.errors < 0 ||
      ![0, 1, 2, 3].includes(r.maxHint) ||
      typeof r.viewedExplanation !== "boolean" ||
      typeof r.resolved !== "boolean" ||
      ![
        null,
        "independent",
        "retried",
        "helped",
        "studied",
        "deferred",
      ].includes(r.mode) ||
      !Array.isArray(r.visited) ||
      r.visited.length > 100 ||
      !r.visited.every((v) => typeof v === "string" && v.length < 100) ||
      !Number.isInteger(r.guideIndex) ||
      r.guideIndex < 0 ||
      r.guideIndex > 1 ||
      !Array.isArray(r.guideEvents) ||
      r.guideEvents.length > 1 ||
      r.guideEvents.some(
        (e) => !["independent", "demonstrated"].includes(e.mode),
      ) ||
      (i < s.index && !r.mode)
    )
      throw Error("科学作答存档无效");
  });
  return s;
}
