export function sprite(id, pose = 0, label = "") {
  const row = Math.max(
    0,
    characters.findIndex((c) => c[0] === id),
  );
  return `<span class="character" role="img" aria-label="${label || characters[row][1]}" style="--cx:${pose * 50}%;--cy:${(row * 100) / 6}%"></span>`;
}
